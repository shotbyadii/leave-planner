/**
 * Utility to compute company initials for fallback icons (e.g. Siemens Healthineers -> SH)
 */
export const getCompanyInitials = (name) => {
  if (!name || typeof name !== 'string') return 'LV';
  const clean = name.trim();
  if (!clean) return 'LV';

  const words = clean.split(/[\s_-]+/).filter(Boolean);
  if (words.length === 1) {
    return words[0].substring(0, 2).toUpperCase();
  }
  return (words[0][0] + words[1][0]).toUpperCase();
};

/**
 * Common domain extensions regex for auto-detecting user typed web addresses
 */
const COMMON_TLD_REGEX = /\.(com|org|net|io|ai|co|in|tech|app|dev|so|me|xyz|uk|ca|de|fr|jp|info|biz|cc|agency|design|cloud|group|global)$/i;

/**
 * Utility to extract domain from company input and return automagical logo URLs.
 * Supports presets, direct URLs, custom domains, and smart brand-domain heuristics.
 */
export const getCompanyLogoUrl = (companyInput) => {
  if (!companyInput || typeof companyInput !== 'string') return null;

  const trimmed = companyInput.trim();
  if (!trimmed) return null;
  const lower = trimmed.toLowerCase();

  // 1. Check preset list first (exact name or domain match)
  const presetMatch = PRESET_COMPANIES.find(c => 
    c.name.toLowerCase() === lower || 
    c.domain.toLowerCase() === lower ||
    c.domain.toLowerCase().replace(/^www\./, '') === lower
  );
  if (presetMatch) {
    return presetMatch.logoUrl;
  }

  // 2. If already a full http/https image/favicon URL
  if (lower.startsWith('http://') || lower.startsWith('https://')) {
    return trimmed;
  }

  // 3. User entered a custom domain (e.g. "myfirm.io", "startup.ai", "acme.co.in")
  if (COMMON_TLD_REGEX.test(trimmed)) {
    const cleanDomain = trimmed.replace(/^[a-z]+:\/\//i, '').split('/')[0];
    return `https://www.google.com/s2/favicons?domain=${encodeURIComponent(cleanDomain.toLowerCase())}&sz=128`;
  }

  // 4. Smart Brand Heuristic:
  // If the user entered a clean company name, construct a domain candidate (.com)
  // to automagically resolve their brand icon via Google's Favicon CDN
  const cleanSlug = lower.replace(/[^a-z0-9]/g, '');
  if (cleanSlug.length >= 2 && cleanSlug.length <= 32) {
    return `https://www.google.com/s2/favicons?domain=${encodeURIComponent(cleanSlug + '.com')}&sz=128`;
  }

  return null;
};

/**
 * Search companies by query string
 * Keeps dropdown populated continuously with rich matches and custom domain option!
 */
export const searchCompanies = (query) => {
  if (!query || typeof query !== 'string') return PRESET_COMPANIES.slice(0, 10);
  const q = query.trim().toLowerCase();
  if (!q) return PRESET_COMPANIES.slice(0, 10);

  // Exact matches first, then prefix matches, then substring matches
  const exact = PRESET_COMPANIES.filter(c => c.name.toLowerCase() === q || c.domain.toLowerCase() === q);
  const prefix = PRESET_COMPANIES.filter(c => (c.name.toLowerCase().startsWith(q) || c.domain.toLowerCase().startsWith(q)) && c.name.toLowerCase() !== q);
  const substring = PRESET_COMPANIES.filter(c => (c.name.toLowerCase().includes(q) || c.domain.toLowerCase().includes(q)) && !c.name.toLowerCase().startsWith(q));

  const results = [...exact, ...prefix, ...substring].slice(0, 10);

  // If exact match is already present as sole result, return just exact match
  if (exact.length === 1 && results.length === 1) {
    return exact;
  }

  // If no exact match in preset list, append custom option so list NEVER collapses
  const hasExact = results.some(c => c.name.toLowerCase() === q || c.domain.toLowerCase() === q);
  if (!hasExact && q.length > 0) {
    const isDomain = COMMON_TLD_REGEX.test(query.trim());
    const domainLabel = isDomain ? query.trim().toLowerCase() : `${q.replace(/[^a-z0-9]/g, '')}.com`;
    results.push({
      name: query.trim(),
      domain: domainLabel,
      logoUrl: getCompanyLogoUrl(query.trim()),
      isCustom: true
    });
  }

  return results;
};
